export type StringKey = keyof typeof en;

export const strings: Record<Lang, Record<StringKey, string>> = { en, es };

/** Fails the build when a key is missing in either language. */
export function assertStringsComplete(): void {
  const enKeys = new Set(Object.keys(en));
  const esKeys = new Set(Object.keys(es));
  const missingInEs = [...enKeys].filter((k) => !esKeys.has(k) || !es[k as StringKey]);
  const missingInEn = [...esKeys].filter((k) => !enKeys.has(k) || !en[k as StringKey]);
  if (missingInEs.length || missingInEn.length) {
    throw new Error(`Strings file incomplete. Missing in es: ${missingInEs.join(', ') || 'none'}. Missing in en: ${missingInEn.join(', ') || 'none'}.`);
  }
}

export function t(lang: Lang, key: StringKey, params: Record<string, string | number> = {}): string {
  const template = strings[lang][key];
  if (template === undefined) throw new Error(`Missing string "${key}" for ${lang}`);
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`Missing parameter "${name}" for string "${key}"`);
    return String(value);
  });
}

/** Looks up a dynamic key such as a Directory entry's description; fails loudly if absent. */
export function tKey(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  return t(lang, key as StringKey, params);
}

export function hasKey(key: string): key is StringKey {
  return key in en;
}
